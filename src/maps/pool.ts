/**
 * The map pool.
 *
 * Every map is authored as a half (team modes) or a quarter (Showdown), so
 * the sides cannot differ — in a symmetrical game, whether one team's cover is
 * better than the other's is the only property that really decides fairness,
 * and this is the one way to make it impossible to get wrong.
 *
 * Density is checked rather than eyeballed. The first draft of this pool was
 * around 14% cover and played as one long sightline: nowhere to approach from,
 * so whoever shot furthest won and nothing else in the game mattered.
 *
 * Legend: `#` wall · `x` crate · `*` bush · `~` water · `o` power cube box
 *         `G` objective · `1` team spawn · `s` free-for-all spawn · `.` open
 */

